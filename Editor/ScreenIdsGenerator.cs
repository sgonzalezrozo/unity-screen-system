using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using ScreenSystem.ScriptableObjects;
using UnityEditor;
using UnityEngine;

namespace ScreenSystem.Editor
{
    /// <summary>
    /// Writes <c>ScreenIds</c>: one constant per screen, so navigation calls are checked at compile time:
    /// <code>await ScreenManager.Instance.GoTo(ScreenIds.ShopMain);</code>
    /// Each constant is named after the screen and holds its ScreenId, which doesn't change when the prefab is
    /// renamed. Renaming or deleting a screen breaks the code that uses it, at compile time instead of at runtime.
    /// Regenerated when ScreenDefinitions change, and written only when the content changes.
    /// </summary>
    public static class ScreenIdsGenerator
    {
        public const string ClassName = "ScreenIds";

        private static readonly HashSet<string> Keywords = new()
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
            "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
            "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
            "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
            "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
            "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
            "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
        };

        [MenuItem("Tools/Screen System/Generate Screen IDs")]
        public static void GenerateFromMenu()
        {
            ScreenSystemSettings settings = ScreenSystemAssets.LoadSettings();
            string path = settings != null ? settings.ScreenIdsPath : ScreenSystemSettings.DefaultScreenIdsPath;
            bool written = WriteIfChanged(force: true);
            Debug.Log(written ? $"[ScreenSystem] Wrote {path}." : $"[ScreenSystem] {path} is up to date.");
        }

        /// <summary>
        /// Regenerates the file from the registry when generation is on. Returns true if the file changed.
        /// <paramref name="force"/> writes even when generation is turned off in the settings.
        /// </summary>
        public static bool WriteIfChanged(bool force = false)
        {
            ScreenSystemSettings settings = ScreenSystemAssets.LoadSettings();
            if (settings == null || (!settings.GenerateScreenIds && !force))
                return false;

            ScreenRegistry registry = ScreenSystemAssets.LoadRegistry();
            if (registry == null)
                return false;

            string path = string.IsNullOrWhiteSpace(settings.ScreenIdsPath) ? ScreenSystemSettings.DefaultScreenIdsPath : settings.ScreenIdsPath;
            string code = Generate(registry.Screens);
            if (File.Exists(path) && File.ReadAllText(path) == code)
                return false;

            Directory.CreateDirectory(Path.GetDirectoryName(path) ?? "Assets");
            File.WriteAllText(path, code);

            // In batch mode the next Editor launch compiles it; importing now would recompile in the middle of a run.
            if (!Application.isBatchMode)
                AssetDatabase.ImportAsset(path);

            return true;
        }

        /// <summary>The C# source for these screens. Pure, so it can be tested.</summary>
        public static string Generate(IEnumerable<ScreenDefinition> screens)
        {
            List<ScreenDefinition> sorted = screens
                .Where(s => s != null && !string.IsNullOrEmpty(s.ScreenId))
                .OrderBy(s => s.ScreenName, System.StringComparer.Ordinal)
                .ThenBy(s => s.ScreenId, System.StringComparer.Ordinal)
                .ToList();

            StringBuilder code = new();
            code.AppendLine("// <auto-generated> Screen System: regenerated when ScreenDefinitions change. Don't edit. </auto-generated>");
            code.AppendLine("namespace ScreenSystem");
            code.AppendLine("{");
            code.AppendLine("    /// <summary>Every screen in the registry. Pass these to GoTo, PopTo and SetRoot instead of strings.</summary>");
            code.AppendLine($"    public static class {ClassName}");
            code.AppendLine("    {");

            HashSet<string> used = new();
            foreach (ScreenDefinition screen in sorted)
            {
                string name = UniqueIdentifier(Identifier(string.IsNullOrEmpty(screen.ScreenName) ? screen.ScreenId : screen.ScreenName), used);
                string path = AssetDatabase.GetAssetPath(screen);
                string where = string.IsNullOrEmpty(path) ? "" : $", {path}";
                code.AppendLine($"        /// <summary>{screen.screenType}{where}</summary>");
                code.AppendLine($"        public const string {name} = \"{Escape(screen.ScreenId)}\";");
                code.AppendLine();
            }

            if (sorted.Count > 0)
                code.Length -= System.Environment.NewLine.Length;

            code.AppendLine("    }");
            code.AppendLine("}");
            return code.ToString();
        }

        /// <summary>A valid C# identifier for a screen name: invalid characters become _, keywords get @.</summary>
        public static string Identifier(string name)
        {
            if (string.IsNullOrEmpty(name))
                return "_";

            StringBuilder id = new();
            foreach (char c in name)
                id.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');

            if (char.IsDigit(id[0]))
                id.Insert(0, '_');

            string result = id.ToString();
            return Keywords.Contains(result) ? "@" + result : result;
        }

        private static string UniqueIdentifier(string name, HashSet<string> used)
        {
            string unique = name;
            for (int i = 2; !used.Add(unique); i++)
                unique = $"{name}_{i}";

            return unique;
        }

        private static string Escape(string value)
            => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}
